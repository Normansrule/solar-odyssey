// Builds site/data/manifest.json (size + SHA-256 of every dataset) and signs it
// with Ed25519 into site/data/manifest.sig. The public key is written to
// site/assets/js/trust.js, which the browser uses to verify the manifest.
//
//   node scripts/sign-manifest.mjs            rebuild + sign (needs the private key)
//   node scripts/sign-manifest.mjs --verify   check files, manifest and signature (no key needed; used in CI)
//
// Private key lookup, in order:
//   $SOLAR_ODYSSEY_SIGNING_KEY  (PEM text, e.g. a GitHub Actions secret)
//   $SOLAR_ODYSSEY_SIGNING_KEY_FILE
//   ~/.config/solar-odyssey/data-signing-key.pem
// If none exists, a new key pair is generated at the last path (mode 600) and
// trust.js is updated: that is a key rotation, and it is printed loudly.
// The private key is never written inside the repository.

import { createHash, generateKeyPairSync, createPrivateKey, createPublicKey, sign, verify } from 'node:crypto';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync, chmodSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dataDir = join(root, 'site', 'data');
const trustFile = join(root, 'site', 'assets', 'js', 'trust.js');
const keyFile = process.env.SOLAR_ODYSSEY_SIGNING_KEY_FILE || join(homedir(), '.config', 'solar-odyssey', 'data-signing-key.pem');

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const rawPub = (pubKey) => pubKey.export({ format: 'der', type: 'spki' }).subarray(-32);
const pubFromRaw = (raw) => createPublicKey({ key: Buffer.concat([Buffer.from('302a300506032b6570032100', 'hex'), raw]), format: 'der', type: 'spki' });

function buildManifest() {
  const files = {};
  for (const f of readdirSync(dataDir).sort()) {
    if (!f.endsWith('.json') || f === 'manifest.json') continue;
    const buf = readFileSync(join(dataDir, f));
    JSON.parse(buf.toString('utf8')); // must be valid JSON
    files[f] = { bytes: buf.length, sha256: sha256(buf) };
  }
  // No timestamps: the manifest is a pure function of the data, so rebuilds are reproducible.
  return Buffer.from(JSON.stringify({ schema: 1, algorithm: 'sha256', signature: 'ed25519', files }, null, 2) + '\n');
}

function readTrustKey() {
  const m = existsSync(trustFile) && readFileSync(trustFile, 'utf8').match(/DATA_PUBLIC_KEY_B64 = '([A-Za-z0-9+/=]+)'/);
  return m ? Buffer.from(m[1], 'base64') : null;
}

function writeTrust(raw) {
  writeFileSync(trustFile, `// Ed25519 public key that signs site/data/manifest.json.
// Generated by scripts/sign-manifest.mjs. Rotating the key rewrites this file.
export const DATA_PUBLIC_KEY_B64 = '${raw.toString('base64')}';
`);
}

function loadPrivateKey() {
  if (process.env.SOLAR_ODYSSEY_SIGNING_KEY) return createPrivateKey(process.env.SOLAR_ODYSSEY_SIGNING_KEY);
  if (existsSync(keyFile)) return createPrivateKey(readFileSync(keyFile));
  const { privateKey } = generateKeyPairSync('ed25519');
  mkdirSync(dirname(keyFile), { recursive: true });
  writeFileSync(keyFile, privateKey.export({ format: 'pem', type: 'pkcs8' }), { mode: 0o600 });
  chmodSync(keyFile, 0o600);
  console.warn(`\n*** No signing key found: generated a NEW Ed25519 key at ${keyFile}.`);
  console.warn('*** site/assets/js/trust.js now holds the new public key (a key rotation). Commit it with the data.\n');
  return privateKey;
}

const manifest = buildManifest();

if (process.argv.includes('--verify')) {
  const problems = [];
  const onDisk = existsSync(join(dataDir, 'manifest.json')) ? readFileSync(join(dataDir, 'manifest.json')) : null;
  if (!onDisk) problems.push('site/data/manifest.json is missing');
  else if (!onDisk.equals(manifest)) problems.push('manifest.json does not match the data files (run `npm run sign`)');
  const sigPath = join(dataDir, 'manifest.sig');
  const pub = readTrustKey();
  if (!pub) problems.push('trust.js has no public key');
  if (!existsSync(sigPath)) problems.push('manifest.sig is missing');
  if (onDisk && pub && existsSync(sigPath)) {
    const ok = verify(null, onDisk, pubFromRaw(pub), Buffer.from(readFileSync(sigPath, 'utf8').trim(), 'base64'));
    if (!ok) problems.push('manifest.sig does not verify against trust.js');
  }
  if (problems.length) { console.error('Data integrity check FAILED:\n  ' + problems.join('\n  ')); process.exit(1); }
  console.log(`data integrity OK: ${Object.keys(JSON.parse(manifest).files).length} datasets, signature valid`);
} else {
  const key = loadPrivateKey();
  const raw = rawPub(createPublicKey(key));
  const current = readTrustKey();
  if (!current || !current.equals(raw)) writeTrust(raw);
  writeFileSync(join(dataDir, 'manifest.json'), manifest);
  writeFileSync(join(dataDir, 'manifest.sig'), sign(null, manifest, key).toString('base64') + '\n');
  console.log(`signed manifest: ${Object.keys(JSON.parse(manifest).files).length} datasets`);
}
