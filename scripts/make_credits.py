#!/usr/bin/env python3
"""Write assets/CREDITS.md: every dataset with its sources and licence, and every vendored
third-party package with its version and licence. Run after build_data.py and vendor.mjs."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
data = ROOT / "site" / "data"
sources = json.loads((data / "sources.json").read_text())
vendor = json.loads((ROOT / "site/vendor/VENDOR.json").read_text())

def cite(sid: str) -> str:
    s = sources.get(sid, {})
    link = f"https://doi.org/{s['doi']}" if s.get("doi") else s.get("url", "")
    who = f"{s['authors']}, " if s.get("authors") else ""
    return f"[{who}{s.get('title', sid)} ({s.get('year', 'n.d.')})]({link})"

out = ["# Credits and licences", "",
       "Generated by `scripts/make_credits.py`; do not edit by hand.", "",
       "Solar Odyssey's own code is MIT-licensed; its lesson text and drawings are CC BY 4.0.", "",
       "## Datasets", "", "| Dataset | Licence | Last verified | Sources |", "|---|---|---|---|"]
for f in sorted(data.glob("*.json")):
    if f.name in ("manifest.json", "sources.json", "glossary.json"):
        continue
    meta = json.loads(f.read_text()).get("meta", {})
    srcs = "<br>".join(cite(s) for s in meta.get("sources", []))
    out.append(f"| `{f.name}`: {meta.get('title', '')} | {meta.get('license', '')} | {meta.get('last_verified', '')} | {srcs} |")
out += ["", "Reference records for every citation on the site: `site/data/sources.json` "
        f"({len(sources)} sources), browsable on the Sources page.", "",
        "## Third-party code and fonts (vendored in site/vendor)", "", "| Package | Version | Licence |", "|---|---|---|"]
for p in vendor["packages"]:
    out.append(f"| [{p['name']}]({p.get('homepage') or 'https://www.npmjs.com/package/' + p['name']}) | {p['version']} | {p['license']} |")
out += ["", "Desktop app: [Tauri](https://tauri.app) (MIT or Apache-2.0). Test tooling: "
        "[pvlib python](https://github.com/pvlib/pvlib-python) (BSD-3-Clause), "
        "[Playwright](https://playwright.dev) (Apache-2.0), pytest (MIT).", ""]
(ROOT / "assets").mkdir(exist_ok=True)
(ROOT / "assets/CREDITS.md").write_text("\n".join(out))
print(f"wrote assets/CREDITS.md")
